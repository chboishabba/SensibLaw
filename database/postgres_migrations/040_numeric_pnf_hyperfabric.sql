    DROP CONSTRAINT IF EXISTS semantic_parser_sentence_digest_key;
ALTER TABLE execution.semantic_parser_sentence
    ADD CONSTRAINT semantic_parser_sentence_digest_key UNIQUE (sentence_digest);

ALTER TABLE execution.semantic_parser_token
    ALTER COLUMN orth_ref DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS token_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS token_digest BYTEA,
    ADD COLUMN IF NOT EXISTS orth_symbol_id BIGINT
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS lemma_symbol_id BIGINT
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS pos_symbol_id BIGINT
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS tag_symbol_id BIGINT
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS dependency_symbol_id BIGINT
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS head_token_id BIGINT,
    ADD COLUMN IF NOT EXISTS morph_set_id BIGINT
        REFERENCES execution.semantic_morph_set(morph_set_id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS representation_version SMALLINT NOT NULL DEFAULT 1;

ALTER TABLE execution.semantic_parser_token
    DROP CONSTRAINT IF EXISTS semantic_parser_token_token_id_key;
ALTER TABLE execution.semantic_parser_token
    ADD CONSTRAINT semantic_parser_token_token_id_key UNIQUE (token_id);

ALTER TABLE execution.semantic_parser_token
    DROP CONSTRAINT IF EXISTS semantic_parser_token_digest_key;
ALTER TABLE execution.semantic_parser_token
    ADD CONSTRAINT semantic_parser_token_digest_key UNIQUE (token_digest);

ALTER TABLE execution.semantic_parser_token
    DROP CONSTRAINT IF EXISTS semantic_parser_token_head_token_id_fkey;
ALTER TABLE execution.semantic_parser_token
    ADD CONSTRAINT semantic_parser_token_head_token_id_fkey
    FOREIGN KEY (head_token_id)
    REFERENCES execution.semantic_parser_token(token_id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE execution.semantic_parser_token
    DROP CONSTRAINT IF EXISTS semantic_parser_token_numeric_representation_ck;
ALTER TABLE execution.semantic_parser_token
    ADD CONSTRAINT semantic_parser_token_numeric_representation_ck CHECK (
        (representation_version = 1 AND orth_ref IS NOT NULL)
        OR
        (
            representation_version = 2
            AND orth_symbol_id IS NOT NULL
            AND orth_ref IS NULL
            AND lemma_ref IS NULL
            AND pos_ref IS NULL
            AND tag_ref IS NULL
            AND dependency_ref IS NULL
        )
    );

