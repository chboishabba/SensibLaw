    PRIMARY KEY (morph_set_id, ordinal),
    UNIQUE (morph_set_id, feature_symbol_id, value_symbol_id)
);

-- Numeric parser occurrence identities. Legacy textual refs remain nullable
-- only for compatibility readers; representation_version=2 forbids their use
-- as authority and requires the numeric columns.
ALTER TABLE execution.semantic_parser_sentence
    ADD COLUMN IF NOT EXISTS sentence_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS sentence_digest BYTEA,
    ADD COLUMN IF NOT EXISTS representation_version SMALLINT NOT NULL DEFAULT 1;

