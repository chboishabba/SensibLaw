CREATE TABLE IF NOT EXISTS execution.semantic_symbol (
    symbol_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind_id SMALLINT NOT NULL
        REFERENCES execution.semantic_symbol_kind(kind_id) ON DELETE RESTRICT,
    symbol_text TEXT NOT NULL,
    symbol_digest BYTEA NOT NULL CHECK (octet_length(symbol_digest) = 32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (kind_id, symbol_text),
    UNIQUE (kind_id, symbol_digest)
);

CREATE INDEX IF NOT EXISTS semantic_symbol_text_idx
    ON execution.semantic_symbol (kind_id, symbol_text);
CREATE INDEX IF NOT EXISTS semantic_symbol_digest_idx
    ON execution.semantic_symbol (kind_id, symbol_digest);

CREATE TABLE IF NOT EXISTS execution.semantic_morph_set (
    morph_set_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    morph_digest BYTEA NOT NULL UNIQUE CHECK (octet_length(morph_digest) = 32),
    member_count SMALLINT NOT NULL CHECK (member_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS execution.semantic_morph_set_member (
    morph_set_id BIGINT NOT NULL
        REFERENCES execution.semantic_morph_set(morph_set_id) ON DELETE CASCADE,
    ordinal SMALLINT NOT NULL CHECK (ordinal >= 0),
    feature_symbol_id BIGINT NOT NULL
