CREATE OR REPLACE FUNCTION execution.rebuild_pnf_interface_ancestors(
    selected_interface_id BIGINT
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    parent_id BIGINT;
    previous_ancestor BIGINT;
    next_ancestor BIGINT;
    power SMALLINT;
    distance_value BIGINT;
BEGIN
    DELETE FROM execution.semantic_pnf_interface_ancestor
     WHERE interface_id = selected_interface_id;
    DELETE FROM execution.semantic_pnf_interface_typed_ancestor
     WHERE interface_id = selected_interface_id;

    SELECT parent_interface_id
      INTO parent_id
      FROM execution.semantic_pnf_interface
     WHERE interface_id = selected_interface_id;

    IF parent_id IS NULL THEN
        RETURN;
    END IF;

    INSERT INTO execution.semantic_pnf_interface_ancestor
        (interface_id, distance_power, ancestor_interface_id, distance)
    VALUES (selected_interface_id, 0, parent_id, 1);

    previous_ancestor := parent_id;
    distance_value := 2;
    FOR power IN 1..62 LOOP
        SELECT ancestor_interface_id
          INTO next_ancestor
          FROM execution.semantic_pnf_interface_ancestor
         WHERE interface_id = previous_ancestor
           AND distance_power = power - 1;
        IF next_ancestor IS NULL THEN
            EXIT;
        END IF;
        INSERT INTO execution.semantic_pnf_interface_ancestor
            (interface_id, distance_power, ancestor_interface_id, distance)
        VALUES (
            selected_interface_id,
            power,
            next_ancestor,
            distance_value
        )
        ON CONFLICT (interface_id, distance_power) DO UPDATE SET
            ancestor_interface_id = EXCLUDED.ancestor_interface_id,
            distance = EXCLUDED.distance;
        previous_ancestor := next_ancestor;
        distance_value := distance_value * 2;
    END LOOP;

    WITH RECURSIVE chain(interface_id, distance) AS (
        SELECT parent_id, 1::BIGINT
        UNION ALL
        SELECT parent.parent_interface_id, chain.distance + 1
          FROM chain
          JOIN execution.semantic_pnf_interface AS parent
            ON parent.interface_id = chain.interface_id
         WHERE parent.parent_interface_id IS NOT NULL
    ),
    typed AS (
        SELECT DISTINCT ON (region.region_kind)
               region.region_kind,
               chain.interface_id,
               chain.distance
          FROM chain
          JOIN execution.semantic_pnf_interface AS interface
            ON interface.interface_id = chain.interface_id
          JOIN execution.semantic_pnf_region AS region
            ON region.region_id = interface.region_id
         ORDER BY region.region_kind, chain.distance
    )
    INSERT INTO execution.semantic_pnf_interface_typed_ancestor
        (interface_id, ancestor_region_kind, ancestor_interface_id, distance)
    SELECT selected_interface_id, region_kind, interface_id, distance
      FROM typed
    ON CONFLICT (interface_id, ancestor_region_kind) DO UPDATE SET
        ancestor_interface_id = EXCLUDED.ancestor_interface_id,
        distance = EXCLUDED.distance;
END;
$$;

CREATE OR REPLACE FUNCTION execution.refresh_pnf_visible_lookup(
    selected_run_ref TEXT,
    selected_document_ref TEXT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    inserted_count BIGINT;
BEGIN
    DELETE FROM execution.semantic_pnf_visible_lookup AS visible
    USING execution.semantic_pnf_interface AS interface,
          execution.semantic_pnf_region AS region
    WHERE visible.interface_id = interface.interface_id
      AND interface.region_id = region.region_id
      AND region.run_ref = selected_run_ref
      AND region.document_ref = selected_document_ref;

    WITH RECURSIVE chain(
        descendant_interface_id,
        ancestor_interface_id,
        distance
    ) AS (
        SELECT interface_id, interface_id, 0::BIGINT
          FROM execution.semantic_pnf_interface AS interface
          JOIN execution.semantic_pnf_region AS region
            ON region.region_id = interface.region_id
         WHERE region.run_ref = selected_run_ref
           AND region.document_ref = selected_document_ref
        UNION ALL
        SELECT chain.descendant_interface_id,
               parent.parent_interface_id,
               chain.distance + 1
          FROM chain
          JOIN execution.semantic_pnf_interface AS parent
            ON parent.interface_id = chain.ancestor_interface_id
         WHERE parent.parent_interface_id IS NOT NULL
    )
    INSERT INTO execution.semantic_pnf_visible_lookup
        (interface_id, key_kind, key_a, key_b,
         target_kind, target_id, source_interface_id,
         ancestor_distance, rank)
    SELECT chain.descendant_interface_id,
           lookup.key_kind,
           lookup.key_a,
           lookup.key_b,
           lookup.target_kind,
           lookup.target_id,
           chain.ancestor_interface_id,
           chain.distance,
           lookup.rank
      FROM chain
      JOIN execution.semantic_pnf_interface_lookup AS lookup
        ON lookup.interface_id = chain.ancestor_interface_id
    ON CONFLICT DO NOTHING;

    GET DIAGNOSTICS inserted_count = ROW_COUNT;
    RETURN inserted_count;
END;
$$;

CREATE OR REPLACE FUNCTION execution.enqueue_numeric_sentence_region()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    parent_region BIGINT;
    inserted_region BIGINT;
    digest_value BYTEA;
BEGIN
    IF NEW.representation_version <> 2 THEN
        RETURN NEW;
    END IF;

    SELECT region_id
      INTO parent_region
      FROM execution.semantic_pnf_region
     WHERE run_ref = NEW.run_ref
       AND document_ref = NEW.document_ref
       AND region_kind IN (3, 5, 6, 7, 8, 10)
       AND start_char <= NEW.start_char
       AND end_char >= NEW.end_char
     ORDER BY
       CASE region_kind
           WHEN 3 THEN 1
           WHEN 5 THEN 2
           WHEN 6 THEN 3
           WHEN 7 THEN 4
           WHEN 8 THEN 5
           ELSE 6
       END,
       end_char - start_char
     LIMIT 1;

    digest_value := digest(
        int8send(NEW.sentence_id)
        || int8send(NEW.start_char)
        || int8send(NEW.end_char),
        'sha256'
    );

    INSERT INTO execution.semantic_pnf_region
        (region_digest, run_ref, document_ref, region_kind,
         start_char, end_char, sequence_no, parent_region_id,
         closure_state, authored_boundary)
    VALUES (
        digest_value,
        NEW.run_ref,
        NEW.document_ref,
        1,
        NEW.start_char,
        NEW.end_char,
        NEW.start_char,
        parent_region,
        1,
        FALSE
    )
    ON CONFLICT (
        run_ref, document_ref, region_kind, start_char, end_char
    ) DO UPDATE SET parent_region_id = COALESCE(
        execution.semantic_pnf_region.parent_region_id,
        EXCLUDED.parent_region_id
    )
    RETURNING region_id INTO inserted_region;

    INSERT INTO execution.semantic_pnf_sentence_region
        (sentence_id, region_id)
    VALUES (NEW.sentence_id, inserted_region)
    ON CONFLICT (sentence_id) DO NOTHING;

    INSERT INTO execution.semantic_pnf_region_edge
        (source_region_id, target_region_id, edge_kind, ordinal)
    SELECT inserted_region, parent_region, 1, NEW.start_char
     WHERE parent_region IS NOT NULL
    ON CONFLICT DO NOTHING;

    INSERT INTO execution.semantic_pnf_work_item
        (work_digest, run_ref, document_ref, region_id,
         operation_id, state_id, priority)
    VALUES (
        digest(
            int8send(inserted_region) || int2send(1::SMALLINT),
            'sha256'
        ),
        NEW.run_ref,
        NEW.document_ref,
        inserted_region,
        1,
        1,
        10
    )
    ON CONFLICT (region_id, operation_id) DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS semantic_numeric_sentence_region
    ON execution.semantic_parser_sentence;
CREATE TRIGGER semantic_numeric_sentence_region
AFTER INSERT ON execution.semantic_parser_sentence
FOR EACH ROW
EXECUTE FUNCTION execution.enqueue_numeric_sentence_region();

