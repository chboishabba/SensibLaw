CREATE TABLE IF NOT EXISTS execution.semantic_pnf_region (
    region_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_digest BYTEA NOT NULL UNIQUE CHECK (octet_length(region_digest) = 32),
    run_ref TEXT NOT NULL
        REFERENCES execution.semantic_run(run_ref) ON DELETE CASCADE,
    document_ref TEXT NOT NULL,
    region_kind SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_region_kind(kind_id) ON DELETE RESTRICT,
    start_char BIGINT NOT NULL CHECK (start_char >= 0),
    end_char BIGINT NOT NULL CHECK (end_char > start_char),
    sequence_no BIGINT NOT NULL CHECK (sequence_no >= 0),
    parent_region_id BIGINT
        REFERENCES execution.semantic_pnf_region(region_id)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    closure_state SMALLINT NOT NULL DEFAULT 1
        REFERENCES execution.semantic_pnf_closure_state(state_id) ON DELETE RESTRICT,
    graph_revision BIGINT NOT NULL DEFAULT 0 CHECK (graph_revision >= 0),
    authored_boundary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    UNIQUE (run_ref, document_ref, region_kind, start_char, end_char)
);

