CREATE TABLE IF NOT EXISTS execution.semantic_pnf_factor_derivation_support (
    derivation_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_factor_derivation(derivation_id)
        ON DELETE CASCADE,
    slot_ordinal SMALLINT NOT NULL CHECK (slot_ordinal >= 0),
    identity_source_object_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_object(object_id) ON DELETE RESTRICT,
    target_entity_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_canonical_entity(entity_id)
        ON DELETE RESTRICT,
    authority_class SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_identity_authority_class(authority_class)
        ON DELETE RESTRICT,
    support_kind SMALLINT NOT NULL CHECK (support_kind IN (1, 2)),
    support_token_id BIGINT,
    identity_witness_ids BIGINT[] NOT NULL,
    PRIMARY KEY (derivation_id, slot_ordinal),
    CHECK (cardinality(identity_witness_ids) > 0),
    CHECK (
        (support_kind = 1 AND support_token_id IS NULL)
        OR (support_kind = 2 AND support_token_id IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS semantic_pnf_factor_derivation_support_source_idx
    ON execution.semantic_pnf_factor_derivation_support
       (identity_source_object_id, target_entity_id, authority_class,
        derivation_id);

CREATE OR REPLACE FUNCTION execution.refresh_numeric_pnf_supported_identity_substitution_derivations(
    selected_run_id BIGINT,
    selected_document_id BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE affected_count BIGINT := 0;
BEGIN
    -- Create one Level-3 derivation per factor/authority only when at least one
    -- argument gains identity applicability through exact token support that is
    -- not already the direct edge object.
    INSERT INTO execution.semantic_pnf_factor_derivation
        (derivation_ref, rule_ref, derivation_kind, derivation_state,
         epistemic_level, authority_class, scope_interface_id,
         conclusion_factor_type_symbol_id, conclusion_predicate_symbol_id,
         modal_state, temporal_state)
    SELECT 'identity-supported-substitution:' || factor.factor_id::TEXT || ':'
               || support.authority_class::TEXT,
           'identity-supported-substitution:v1',
           1,
           2,
           3,
           support.authority_class,
           interface.interface_id,
           factor.factor_type_symbol_id,
           factor.predicate_symbol_id,
           factor.modal_state,
           factor.temporal_state
      FROM execution.semantic_pnf_factor AS factor
      JOIN execution.semantic_pnf_region AS region
        ON region.region_id = factor.region_id
      JOIN execution.semantic_pnf_interface AS interface
        ON interface.region_id = region.region_id
      JOIN execution.semantic_pnf_factor_identity_support_unique_v1 AS support
        ON support.factor_id = factor.factor_id
       AND support.support_kind = 2
     WHERE region.run_id = selected_run_id
       AND region.document_id = selected_document_id
     GROUP BY factor.factor_id, support.authority_class,
              interface.interface_id,
              factor.factor_type_symbol_id,
              factor.predicate_symbol_id,
              factor.modal_state,
              factor.temporal_state
    ON CONFLICT (derivation_ref) DO NOTHING;

    INSERT INTO execution.semantic_pnf_factor_derivation_premise
        (derivation_id, premise_ordinal, factor_id)
    SELECT derivation.derivation_id, 0, factor.factor_id
      FROM execution.semantic_pnf_factor_derivation AS derivation
      JOIN execution.semantic_pnf_factor AS factor
        ON derivation.derivation_ref =
           'identity-supported-substitution:' || factor.factor_id::TEXT || ':'
           || derivation.authority_class::TEXT
      JOIN execution.semantic_pnf_region AS region
        ON region.region_id = factor.region_id
     WHERE derivation.rule_ref = 'identity-supported-substitution:v1'
       AND region.run_id = selected_run_id
       AND region.document_id = selected_document_id
    ON CONFLICT DO NOTHING;

    INSERT INTO execution.semantic_pnf_factor_derivation_argument
        (derivation_id, slot_ordinal, role_symbol_id, source_object_id,
         local_object_id, identity_entity_id, identity_witness_ids)
    SELECT derivation.derivation_id,
           edge.slot_ordinal,
           edge.role_symbol_id,
           edge.object_id,
           CASE WHEN support.target_entity_id IS NULL
                THEN edge.object_id ELSE NULL END,
           support.target_entity_id,
           support.witness_ids
      FROM execution.semantic_pnf_factor_derivation AS derivation
      JOIN execution.semantic_pnf_factor_derivation_premise AS premise
        ON premise.derivation_id = derivation.derivation_id
       AND premise.premise_ordinal = 0
      JOIN execution.semantic_pnf_factor AS factor
        ON factor.factor_id = premise.factor_id
      JOIN execution.semantic_pnf_region AS region
        ON region.region_id = factor.region_id
      JOIN execution.semantic_pnf_hyperedge AS edge
        ON edge.factor_id = factor.factor_id
      LEFT JOIN execution.semantic_pnf_factor_identity_support_unique_v1 AS support
        ON support.factor_id = edge.factor_id
       AND support.slot_ordinal = edge.slot_ordinal
       AND support.authority_class = derivation.authority_class
     WHERE derivation.rule_ref = 'identity-supported-substitution:v1'
       AND region.run_id = selected_run_id
       AND region.document_id = selected_document_id
    ON CONFLICT (derivation_id, slot_ordinal) DO NOTHING;

    INSERT INTO execution.semantic_pnf_factor_derivation_support
        (derivation_id, slot_ordinal, identity_source_object_id,
         target_entity_id, authority_class, support_kind, support_token_id,
         identity_witness_ids)
    SELECT derivation.derivation_id,
           edge.slot_ordinal,
           support.identity_source_object_id,
           support.target_entity_id,
           support.authority_class,
           support.support_kind,
           support.support_token_id,
           support.witness_ids
      FROM execution.semantic_pnf_factor_derivation AS derivation
      JOIN execution.semantic_pnf_factor_derivation_premise AS premise
        ON premise.derivation_id = derivation.derivation_id
       AND premise.premise_ordinal = 0
      JOIN execution.semantic_pnf_factor AS factor
        ON factor.factor_id = premise.factor_id
      JOIN execution.semantic_pnf_region AS region
        ON region.region_id = factor.region_id
      JOIN execution.semantic_pnf_hyperedge AS edge
        ON edge.factor_id = factor.factor_id
      JOIN execution.semantic_pnf_factor_identity_support_unique_v1 AS support
        ON support.factor_id = edge.factor_id
       AND support.slot_ordinal = edge.slot_ordinal
       AND support.authority_class = derivation.authority_class
     WHERE derivation.rule_ref = 'identity-supported-substitution:v1'
       AND region.run_id = selected_run_id
       AND region.document_id = selected_document_id
    ON CONFLICT (derivation_id, slot_ordinal) DO NOTHING;

    SELECT count(*)
      INTO affected_count
      FROM execution.semantic_pnf_factor_derivation AS derivation
      JOIN execution.semantic_pnf_factor_derivation_premise AS premise
        ON premise.derivation_id = derivation.derivation_id
      JOIN execution.semantic_pnf_factor AS factor
        ON factor.factor_id = premise.factor_id
      JOIN execution.semantic_pnf_region AS region
        ON region.region_id = factor.region_id
     WHERE derivation.rule_ref = 'identity-supported-substitution:v1'
       AND region.run_id = selected_run_id
       AND region.document_id = selected_document_id;
    RETURN affected_count;
END;
$$;

-- Preserve the existing semantic-derivation API and wire structural-support
-- applicability into the normal post-identity derivation refresh.
CREATE OR REPLACE FUNCTION execution.refresh_numeric_pnf_semantic_derivations(
    selected_run_id BIGINT,
    selected_document_id BIGINT
)
RETURNS TABLE (
    identity_witness_count BIGINT,
    identity_derivation_count BIGINT,
    composition_candidate_count BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE supported_identity_derivation_count BIGINT := 0;
BEGIN
    identity_witness_count := execution.refresh_numeric_pnf_identity_witnesses(
        selected_run_id,
        selected_document_id
    );
    identity_derivation_count :=
        execution.refresh_numeric_pnf_identity_substitution_derivations(
            selected_run_id,
            selected_document_id
        );
    supported_identity_derivation_count :=
        execution.refresh_numeric_pnf_supported_identity_substitution_derivations(
            selected_run_id,
            selected_document_id
        );
    identity_derivation_count :=
        identity_derivation_count + supported_identity_derivation_count;
    composition_candidate_count :=
        execution.refresh_numeric_pnf_factor_composition_candidates(
            selected_run_id,
            selected_document_id,
            16
        );
    RETURN NEXT;
END;
$$;

-- Alignment audit -------------------------------------------------------------
CREATE OR REPLACE VIEW execution.semantic_pnf_identity_factor_alignment_audit_v1 AS
SELECT projection.source_object_id,
       projection.target_entity_id,
       projection.authority_class,
       source_region.run_id,
       source_region.document_id,
       CASE
           WHEN EXISTS (
               SELECT 1
                 FROM execution.semantic_pnf_hyperedge AS edge
                WHERE edge.object_id = projection.source_object_id
           ) THEN 'direct_factor_participant'
           WHEN EXISTS (
               SELECT 1
                 FROM execution.semantic_pnf_factor_identity_support_v1 AS support
                WHERE support.identity_source_object_id = projection.source_object_id
                  AND support.authority_class = projection.authority_class
                  AND support.target_entity_id = projection.target_entity_id
                  AND support.support_kind = 2
           ) THEN 'exact_token_structural_support'
           WHEN EXISTS (
               SELECT 1
                 FROM execution.semantic_pnf_factor AS factor
                WHERE factor.region_id = source_object.region_id
           ) THEN 'same_region_unbridged'
           ELSE 'no_structural_bridge'
       END AS alignment_class
  FROM execution.semantic_pnf_identity_projection AS projection
  JOIN execution.semantic_pnf_object AS source_object
    ON source_object.object_id = projection.source_object_id
  JOIN execution.semantic_pnf_region AS source_region
    ON source_region.region_id = source_object.region_id;

CREATE OR REPLACE VIEW execution.semantic_pnf_identity_factor_alignment_summary_v1 AS
SELECT run_id,
       document_id,
       alignment_class,
       count(*)::BIGINT AS projection_count
  FROM execution.semantic_pnf_identity_factor_alignment_audit_v1
 GROUP BY run_id, document_id, alignment_class;

-- Typed-demand funnel ----------------------------------------------------------
CREATE OR REPLACE VIEW execution.semantic_pnf_demand_funnel_v1 AS
SELECT demand.demand_id,
       source_region.run_id,
       source_region.document_id,
       demand.state AS demand_state,
       count(DISTINCT universe.target_kind::TEXT || ':' || universe.target_id::TEXT)
           AS represented_candidate_count,
       count(DISTINCT CASE WHEN candidate_state.active
             THEN candidate_state.target_kind::TEXT || ':' || candidate_state.target_id::TEXT END)
           AS active_candidate_count,
       count(DISTINCT CASE WHEN candidate_state.execution_residual
             THEN candidate_state.target_kind::TEXT || ':' || candidate_state.target_id::TEXT END)
           AS residual_candidate_count,
       count(DISTINCT CASE WHEN candidate_state.refuted
             THEN candidate_state.target_kind::TEXT || ':' || candidate_state.target_id::TEXT END)
           AS refuted_candidate_count,
       count(DISTINCT evidence.evidence_id) AS evidence_count,
       count(DISTINCT CASE WHEN admission.admission_state = 2
             THEN witness.witness_id END) AS admitted_identity_witness_count,
       COALESCE(open_world.outside_model_possible, TRUE) AS outside_model_possible,
       COALESCE(open_world.resource_limited, FALSE) AS resource_limited
  FROM execution.semantic_pnf_demand AS demand
  JOIN execution.semantic_pnf_region AS source_region
    ON source_region.region_id = demand.source_region_id
  LEFT JOIN execution.semantic_pnf_candidate_universe AS universe
    ON universe.demand_id = demand.demand_id
  LEFT JOIN execution.semantic_pnf_candidate_state_v1 AS candidate_state
    ON candidate_state.demand_id = universe.demand_id
   AND candidate_state.target_kind = universe.target_kind
   AND candidate_state.target_id = universe.target_id
  LEFT JOIN execution.semantic_pnf_candidate_evidence AS evidence
    ON evidence.demand_id = demand.demand_id
  LEFT JOIN execution.semantic_pnf_identity_witness AS witness
    ON witness.demand_id = demand.demand_id
  LEFT JOIN execution.semantic_pnf_identity_witness_admission AS admission
    ON admission.witness_id = witness.witness_id
  LEFT JOIN execution.semantic_pnf_demand_open_world_state AS open_world
    ON open_world.demand_id = demand.demand_id
 GROUP BY demand.demand_id,
          source_region.run_id,
          source_region.document_id,
          demand.state,
          open_world.outside_model_possible,
          open_world.resource_limited;

CREATE OR REPLACE VIEW execution.semantic_pnf_candidate_compression_v1 AS
SELECT demand.demand_id,
       source_region.run_id,
       source_region.document_id,
       count(universe.target_id)::BIGINT AS represented_candidate_count,
       count(*) FILTER (WHERE state.active)::BIGINT AS active_candidate_count,
       count(*) FILTER (WHERE state.execution_residual)::BIGINT
           AS residual_candidate_count,
       count(*) FILTER (WHERE state.refuted)::BIGINT AS refuted_candidate_count,
       CASE WHEN count(universe.target_id) = 0 THEN NULL
            ELSE count(*) FILTER (WHERE state.active)::NUMERIC
                 / count(universe.target_id)::NUMERIC
       END AS active_compression_ratio,
       COALESCE(open_world.outside_model_possible, TRUE) AS outside_model_possible
  FROM execution.semantic_pnf_demand AS demand
  JOIN execution.semantic_pnf_region AS source_region
    ON source_region.region_id = demand.source_region_id
  LEFT JOIN execution.semantic_pnf_candidate_universe AS universe
    ON universe.demand_id = demand.demand_id
  LEFT JOIN execution.semantic_pnf_candidate_state_v1 AS state
    ON state.demand_id = universe.demand_id
   AND state.target_kind = universe.target_kind
   AND state.target_id = universe.target_id
  LEFT JOIN execution.semantic_pnf_demand_open_world_state AS open_world
    ON open_world.demand_id = demand.demand_id
 GROUP BY demand.demand_id,
          source_region.run_id,
          source_region.document_id,
          open_world.outside_model_possible;

-- Performance / retrieval observatory -----------------------------------------
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_runtime_stage_measurement (
    measurement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_ref TEXT NOT NULL UNIQUE,
    workload_ref TEXT NOT NULL,
    run_id BIGINT,
    document_id BIGINT,
    stage_name TEXT NOT NULL,
    input_units BIGINT NOT NULL CHECK (input_units >= 0),
    generated_units BIGINT NOT NULL CHECK (generated_units >= 0),
    retained_units BIGINT NOT NULL CHECK (retained_units >= 0),
    output_units BIGINT NOT NULL CHECK (output_units >= 0),
    work_units BIGINT NOT NULL CHECK (work_units >= 0),
    elapsed_microseconds BIGINT NOT NULL CHECK (elapsed_microseconds >= 0),
    peak_memory_bytes BIGINT CHECK (peak_memory_bytes IS NULL OR peak_memory_bytes >= 0),
    measured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS semantic_pnf_runtime_stage_workload_idx
    ON execution.semantic_pnf_runtime_stage_measurement
       (workload_ref, stage_name, measured_at, measurement_id);

-- retrieval_kind: 1=exact numeric/equality, 2=object-token support,
-- 3=ordered/range (B-tree), 4=PG FTS lexical normalization/stemming,
-- 5=prefix/structural address, 6=vector neighbourhood proposal.
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_retrieval_measurement (
    measurement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_ref TEXT NOT NULL UNIQUE,
    workload_ref TEXT NOT NULL,
    retrieval_kind SMALLINT NOT NULL CHECK (retrieval_kind BETWEEN 1 AND 6),
    universe_units BIGINT NOT NULL CHECK (universe_units >= 0),
    frontier_units BIGINT NOT NULL CHECK (frontier_units >= 0),
    probe_microseconds BIGINT NOT NULL CHECK (probe_microseconds >= 0),
    downstream_work_units BIGINT NOT NULL CHECK (downstream_work_units >= 0),
    exact_downstream_required BOOLEAN NOT NULL DEFAULT FALSE,
    measured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (frontier_units <= universe_units),
    CHECK (retrieval_kind <> 6 OR exact_downstream_required)
);
CREATE INDEX IF NOT EXISTS semantic_pnf_retrieval_workload_idx
    ON execution.semantic_pnf_retrieval_measurement
       (workload_ref, retrieval_kind, measured_at, measurement_id);

CREATE OR REPLACE VIEW execution.semantic_pnf_runtime_parser_dominance_v1 AS
WITH latest AS (
    SELECT DISTINCT ON (workload_ref, stage_name)
           workload_ref, stage_name, elapsed_microseconds, work_units,
           measurement_id
      FROM execution.semantic_pnf_runtime_stage_measurement
     WHERE stage_name IN ('spacy', 'post_parser_total')
     ORDER BY workload_ref, stage_name, measurement_id DESC
)
SELECT parser.workload_ref,
       parser.elapsed_microseconds AS parser_elapsed_microseconds,
       semantics.elapsed_microseconds AS post_parser_elapsed_microseconds,
       parser.work_units AS parser_work_units,
       semantics.work_units AS post_parser_work_units,
       CASE WHEN semantics.elapsed_microseconds = 0 THEN NULL
            ELSE parser.elapsed_microseconds::NUMERIC
                 / semantics.elapsed_microseconds::NUMERIC
       END AS elapsed_dominance_ratio,
       CASE WHEN semantics.work_units = 0 THEN NULL
            ELSE parser.work_units::NUMERIC / semantics.work_units::NUMERIC
       END AS work_dominance_ratio
  FROM latest AS parser
  JOIN latest AS semantics
    ON semantics.workload_ref = parser.workload_ref
   AND semantics.stage_name = 'post_parser_total'
 WHERE parser.stage_name = 'spacy';

COMMIT;
