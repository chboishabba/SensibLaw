  FROM execution.semantic_pnf_demand_candidate AS candidate
ON CONFLICT (demand_id, target_kind, target_id, evidence_ref) DO NOTHING;

-- Candidate-state and horizon views -------------------------------------------

CREATE OR REPLACE VIEW execution.semantic_pnf_candidate_latest_execution AS
SELECT DISTINCT ON (demand_id, target_kind, target_id)
       demand_id, target_kind, target_id, event_id, event_kind,
       active_budget, reason_ref, created_at
  FROM execution.semantic_pnf_candidate_execution_event
 ORDER BY demand_id, target_kind, target_id, event_id DESC;

CREATE OR REPLACE VIEW execution.semantic_pnf_candidate_latest_admissibility AS
SELECT DISTINCT ON (demand_id, target_kind, target_id)
       demand_id, target_kind, target_id, event_id, event_kind,
       evidence_id, created_at
  FROM execution.semantic_pnf_candidate_admissibility_event
 ORDER BY demand_id, target_kind, target_id, event_id DESC;

CREATE OR REPLACE VIEW execution.semantic_pnf_candidate_latest_preference AS
SELECT DISTINCT ON (demand_id, target_kind, target_id, horizon)
       demand_id, target_kind, target_id, horizon, revision,
       preferred, margin, evidence_count, preference_id
  FROM execution.semantic_pnf_candidate_preference
 ORDER BY demand_id, target_kind, target_id, horizon, revision DESC,
          preference_id DESC;

CREATE OR REPLACE VIEW execution.semantic_pnf_candidate_universe AS
SELECT observation.demand_id,
       observation.target_kind,
       observation.target_id,
       min(observation.observation_id) AS first_observation_id,
       max(observation.observation_id) AS latest_observation_id
  FROM execution.semantic_pnf_demand_candidate_observation AS observation
 GROUP BY observation.demand_id, observation.target_kind, observation.target_id;

CREATE OR REPLACE VIEW execution.semantic_pnf_candidate_state_v1 AS
SELECT universe.demand_id,
       universe.target_kind,
       universe.target_id,
       TRUE AS represented_possible,
       current_candidate.demand_id IS NOT NULL
           AND COALESCE(execution_state.event_kind, 1) IN (1, 3)
           AS active,
       COALESCE(execution_state.event_kind IN (2, 4, 5), FALSE)
           AS execution_residual,
       COALESCE(admissibility.event_kind = 1, FALSE) AS refuted,
       NOT COALESCE(admissibility.event_kind = 1, FALSE) AS admissible,
       execution_state.reason_ref AS execution_reason_ref,
       admissibility.evidence_id AS admissibility_evidence_id
  FROM execution.semantic_pnf_candidate_universe AS universe
  LEFT JOIN execution.semantic_pnf_demand_candidate AS current_candidate
    ON current_candidate.demand_id = universe.demand_id
   AND current_candidate.target_kind = universe.target_kind
   AND current_candidate.target_id = universe.target_id
  LEFT JOIN execution.semantic_pnf_candidate_latest_execution AS execution_state
    ON execution_state.demand_id = universe.demand_id
   AND execution_state.target_kind = universe.target_kind
   AND execution_state.target_id = universe.target_id
  LEFT JOIN execution.semantic_pnf_candidate_latest_admissibility AS admissibility
    ON admissibility.demand_id = universe.demand_id
   AND admissibility.target_kind = universe.target_kind
   AND admissibility.target_id = universe.target_id;

CREATE OR REPLACE VIEW execution.semantic_pnf_candidate_evidence_horizon_v1 AS
WITH horizon(horizon) AS (
    VALUES (3::SMALLINT), (6::SMALLINT), (9::SMALLINT)
)
SELECT universe.demand_id,
       universe.target_kind,
       universe.target_id,
       horizon.horizon,
       COALESCE(sum(evidence.signed_residual), 0)::BIGINT AS signed_residual,
       sign(COALESCE(sum(evidence.signed_residual), 0))::SMALLINT AS phase,
       count(evidence.evidence_id)::BIGINT AS evidence_count
  FROM execution.semantic_pnf_candidate_universe AS universe
 CROSS JOIN horizon
  LEFT JOIN execution.semantic_pnf_candidate_evidence AS evidence
    ON evidence.demand_id = universe.demand_id
   AND evidence.target_kind = universe.target_kind
   AND evidence.target_id = universe.target_id
   AND evidence.horizon <= horizon.horizon
 GROUP BY universe.demand_id, universe.target_kind, universe.target_id,
          horizon.horizon;

