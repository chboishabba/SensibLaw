       SELECT 1
         FROM execution.semantic_pnf_demand_candidate_observation AS observation
        WHERE observation.demand_id = candidate.demand_id
          AND observation.target_kind = candidate.target_kind
          AND observation.target_id = candidate.target_id
   );

