-- Consumer-indexed, reopenable runtime carrier --------------------------------
--
-- Agda reference contract:
--   F = represented candidate fibre (the existing demand_candidate relation)
--   P = active bounded execution surface
--   Q = represented but inactive/reopenable candidates
--   R = other represented unresolved residual structure
--   O = explicit outside-model/open-world ignorance
--
-- The current demand_candidate table remains the hot execution surface.  It is
-- intentionally NOT promoted to semantic truth: planner replacement is logged
-- as an execution event and candidate history survives replanning.

CREATE TABLE IF NOT EXISTS execution.semantic_pnf_demand_candidate_observation (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_demand(demand_id) ON DELETE CASCADE,
    target_kind SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_target_kind(kind_id) ON DELETE RESTRICT,
    target_id BIGINT NOT NULL,
    observation_kind SMALLINT NOT NULL CHECK (observation_kind IN (1, 2)),
    planning_ordinal SMALLINT,
    source_interface_id BIGINT
        REFERENCES execution.semantic_pnf_interface(interface_id) ON DELETE SET NULL,
    ancestor_distance BIGINT,
    index_rank BIGINT,
    candidate_score DOUBLE PRECISION,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS semantic_pnf_candidate_observation_candidate_idx
    ON execution.semantic_pnf_demand_candidate_observation
       (demand_id, target_kind, target_id, observation_id);
CREATE INDEX IF NOT EXISTS semantic_pnf_candidate_observation_time_idx
    ON execution.semantic_pnf_demand_candidate_observation
       (demand_id, observed_at, observation_id);

-- Fine evidence is append-only in ordinary operation.  The signed residual is
-- the authoritative numeric evidence coordinate; -1/0/+1 is derived by views.
-- Horizon 3/6/9 is cumulative over one candidate fibre, not three candidate
-- searches.  Family 1=local structural, 2=discourse/temporal, 3=external.
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_candidate_evidence (
    evidence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_demand(demand_id) ON DELETE CASCADE,
    target_kind SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_target_kind(kind_id) ON DELETE RESTRICT,
    target_id BIGINT NOT NULL,
    evidence_ref TEXT NOT NULL,
    evidence_family SMALLINT NOT NULL CHECK (evidence_family IN (1, 2, 3)),
    horizon SMALLINT NOT NULL CHECK (horizon IN (3, 6, 9)),
    signed_residual BIGINT NOT NULL,
    evidence_kind TEXT NOT NULL,
    provenance_ref TEXT,
    source_interface_id BIGINT
        REFERENCES execution.semantic_pnf_interface(interface_id) ON DELETE SET NULL,
    source_region_id BIGINT
        REFERENCES execution.semantic_pnf_region(region_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (demand_id, target_kind, target_id, evidence_ref),
    CHECK (
        (evidence_family = 1 AND horizon = 3)
        OR (evidence_family = 2 AND horizon = 6)
        OR (evidence_family = 3 AND horizon = 9)
    )
);
CREATE INDEX IF NOT EXISTS semantic_pnf_candidate_evidence_horizon_idx
    ON execution.semantic_pnf_candidate_evidence
       (demand_id, target_kind, target_id, horizon, evidence_id);
CREATE INDEX IF NOT EXISTS semantic_pnf_candidate_evidence_provenance_idx
    ON execution.semantic_pnf_candidate_evidence
       (provenance_ref, evidence_id)
    WHERE provenance_ref IS NOT NULL;

-- Execution events are explicitly non-semantic.  1=activate, 2=prune,
-- 3=reopen, 4=resource-limited, 5=planner-superseded.  None refutes a candidate.
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_candidate_execution_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_demand(demand_id) ON DELETE CASCADE,
    target_kind SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_target_kind(kind_id) ON DELETE RESTRICT,
    target_id BIGINT NOT NULL,
    event_kind SMALLINT NOT NULL CHECK (event_kind BETWEEN 1 AND 5),
    active_budget INTEGER CHECK (active_budget IS NULL OR active_budget > 0),
    reason_ref TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS semantic_pnf_candidate_execution_latest_idx
    ON execution.semantic_pnf_candidate_execution_event
       (demand_id, target_kind, target_id, event_id DESC);

-- Semantic refutation/restoration is a DIFFERENT event family and every event
-- requires a concrete evidence row.  1=refute, 2=restore admissibility.
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_candidate_admissibility_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_demand(demand_id) ON DELETE CASCADE,
    target_kind SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_target_kind(kind_id) ON DELETE RESTRICT,
    target_id BIGINT NOT NULL,
    event_kind SMALLINT NOT NULL CHECK (event_kind IN (1, 2)),
    evidence_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_candidate_evidence(evidence_id)
        ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS semantic_pnf_candidate_admissibility_latest_idx
    ON execution.semantic_pnf_candidate_admissibility_event
       (demand_id, target_kind, target_id, event_id DESC);

-- Inductive preference is revisioned and remains non-proof.  It is intentionally
-- disjoint from identity_witness / identity_witness_admission.
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_candidate_preference (
    preference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_demand(demand_id) ON DELETE CASCADE,
    target_kind SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_target_kind(kind_id) ON DELETE RESTRICT,
    target_id BIGINT NOT NULL,
    horizon SMALLINT NOT NULL CHECK (horizon IN (3, 6, 9)),
    revision BIGINT NOT NULL CHECK (revision > 0),
    preferred BOOLEAN NOT NULL,
    margin BIGINT NOT NULL DEFAULT 0,
    evidence_count BIGINT NOT NULL DEFAULT 0 CHECK (evidence_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (demand_id, target_kind, target_id, horizon, revision)
);
CREATE INDEX IF NOT EXISTS semantic_pnf_candidate_preference_latest_idx
    ON execution.semantic_pnf_candidate_preference
       (demand_id, target_kind, target_id, horizon, revision DESC);

-- Open-world closure cannot be asserted merely because current candidates sum
-- to a normalized unit.  A demand is open-world by default.  Closing that door
-- requires an explicit coverage witness reference.
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_demand_open_world_state (
    demand_id BIGINT PRIMARY KEY
        REFERENCES execution.semantic_pnf_demand(demand_id) ON DELETE CASCADE,
    outside_model_possible BOOLEAN NOT NULL DEFAULT TRUE,
    coverage_witness_ref TEXT,
    represented_residual_count BIGINT NOT NULL DEFAULT 0
        CHECK (represented_residual_count >= 0),
    resource_limited BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (outside_model_possible OR coverage_witness_ref IS NOT NULL)
);

INSERT INTO execution.semantic_pnf_demand_open_world_state (demand_id)
SELECT demand_id
  FROM execution.semantic_pnf_demand
ON CONFLICT (demand_id) DO NOTHING;

CREATE OR REPLACE FUNCTION execution.seed_numeric_pnf_open_world_state()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO execution.semantic_pnf_demand_open_world_state (demand_id)
    VALUES (NEW.demand_id)
    ON CONFLICT (demand_id) DO NOTHING;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS semantic_pnf_demand_open_world_seed
    ON execution.semantic_pnf_demand;
CREATE TRIGGER semantic_pnf_demand_open_world_seed
AFTER INSERT ON execution.semantic_pnf_demand
FOR EACH ROW EXECUTE FUNCTION execution.seed_numeric_pnf_open_world_state();

-- Consumer/model-relative mass accounting.  These exact integer masses are not
-- probabilities and do not assert that the represented candidate universe is
-- complete.  mass_kind: 1=candidate weight, 2=represented provenance,
-- 3=consumer/task relevance.
CREATE TABLE IF NOT EXISTS execution.semantic_pnf_demand_relevance_accounting (
    accounting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_demand(demand_id) ON DELETE CASCADE,
    consumer_ref TEXT NOT NULL,
    mass_kind SMALLINT NOT NULL CHECK (mass_kind IN (1, 2, 3)),
    horizon SMALLINT NOT NULL CHECK (horizon IN (3, 6, 9)),
    active_mass BIGINT NOT NULL CHECK (active_mass >= 0),
    residual_candidate_mass BIGINT NOT NULL CHECK (residual_candidate_mass >= 0),
    represented_residual_mass BIGINT NOT NULL CHECK (represented_residual_mass >= 0),
    outside_model_mass BIGINT NOT NULL CHECK (outside_model_mass >= 0),
    total_mass BIGINT NOT NULL CHECK (total_mass > 0),
    measurement_ref TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        active_mass + residual_candidate_mass
        + represented_residual_mass + outside_model_mass = total_mass
    )
);
CREATE INDEX IF NOT EXISTS semantic_pnf_relevance_accounting_demand_idx
    ON execution.semantic_pnf_demand_relevance_accounting
       (demand_id, consumer_ref, horizon, accounting_id DESC);

-- Planner hot-surface lifecycle ------------------------------------------------
-- Existing planners DELETE + INSERT demand_candidate rows.  Preserve those
-- transitions rather than interpreting DELETE as semantic disappearance.

CREATE OR REPLACE FUNCTION execution.observe_numeric_pnf_candidate_insert()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO execution.semantic_pnf_demand_candidate_observation
        (demand_id, target_kind, target_id, observation_kind,
         planning_ordinal, source_interface_id, ancestor_distance,
         index_rank, candidate_score)
    VALUES
        (NEW.demand_id, NEW.target_kind, NEW.target_id, 1,
         NEW.ordinal, NEW.source_interface_id, NEW.ancestor_distance,
         NEW.index_rank, NEW.candidate_score);

    INSERT INTO execution.semantic_pnf_candidate_execution_event
        (demand_id, target_kind, target_id, event_kind, reason_ref)
    VALUES (NEW.demand_id, NEW.target_kind, NEW.target_id, 1, 'planner-active');

    -- Candidate generation is neutral structural evidence: membership in F is
    -- recorded without converting the legacy floating candidate_score to a
    -- semantic signed residual.
    INSERT INTO execution.semantic_pnf_candidate_evidence
        (demand_id, target_kind, target_id, evidence_ref,
         evidence_family, horizon, signed_residual, evidence_kind,
         provenance_ref, source_interface_id)
    VALUES
        (NEW.demand_id, NEW.target_kind, NEW.target_id,
         'planner-membership:' || NEW.target_kind::TEXT || ':' || NEW.target_id::TEXT,
         1, 3, 0, 'candidate_generation',
         'semantic_pnf_demand_candidate', NEW.source_interface_id)
    ON CONFLICT (demand_id, target_kind, target_id, evidence_ref) DO NOTHING;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION execution.observe_numeric_pnf_candidate_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO execution.semantic_pnf_demand_candidate_observation
        (demand_id, target_kind, target_id, observation_kind,
         planning_ordinal, source_interface_id, ancestor_distance,
         index_rank, candidate_score)
    VALUES
        (OLD.demand_id, OLD.target_kind, OLD.target_id, 2,
         OLD.ordinal, OLD.source_interface_id, OLD.ancestor_distance,
         OLD.index_rank, OLD.candidate_score);

    INSERT INTO execution.semantic_pnf_candidate_execution_event
        (demand_id, target_kind, target_id, event_kind, reason_ref)
    VALUES
        (OLD.demand_id, OLD.target_kind, OLD.target_id, 5,
         'planner-replan-superseded');
    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS semantic_pnf_candidate_observe_insert
    ON execution.semantic_pnf_demand_candidate;
CREATE TRIGGER semantic_pnf_candidate_observe_insert
AFTER INSERT ON execution.semantic_pnf_demand_candidate
FOR EACH ROW EXECUTE FUNCTION execution.observe_numeric_pnf_candidate_insert();

DROP TRIGGER IF EXISTS semantic_pnf_candidate_observe_delete
    ON execution.semantic_pnf_demand_candidate;
CREATE TRIGGER semantic_pnf_candidate_observe_delete
BEFORE DELETE ON execution.semantic_pnf_demand_candidate
FOR EACH ROW EXECUTE FUNCTION execution.observe_numeric_pnf_candidate_delete();

