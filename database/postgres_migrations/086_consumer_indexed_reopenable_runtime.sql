CREATE OR REPLACE FUNCTION execution.record_numeric_pnf_candidate_admissibility(
    selected_demand_id BIGINT,
    selected_target_kind SMALLINT,
    selected_target_id BIGINT,
    selected_event_kind SMALLINT,
    selected_evidence_id BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE inserted_event BIGINT;
BEGIN
    IF selected_event_kind NOT IN (1, 2) THEN
        RAISE EXCEPTION 'admissibility event kind must be 1=refute or 2=restore';
    END IF;
    IF NOT EXISTS (
        SELECT 1
          FROM execution.semantic_pnf_candidate_evidence AS evidence
         WHERE evidence.evidence_id = selected_evidence_id
           AND evidence.demand_id = selected_demand_id
           AND evidence.target_kind = selected_target_kind
           AND evidence.target_id = selected_target_id
    ) THEN
        RAISE EXCEPTION 'admissibility event requires evidence for the same candidate';
    END IF;
    INSERT INTO execution.semantic_pnf_candidate_admissibility_event
        (demand_id, target_kind, target_id, event_kind, evidence_id)
    VALUES
        (selected_demand_id, selected_target_kind, selected_target_id,
         selected_event_kind, selected_evidence_id)
    RETURNING event_id INTO inserted_event;
    RETURN inserted_event;
END;
$$;

-- Exact representation support -> factor applicability ------------------------
-- Reuse semantic_pnf_object_token_support.  Sharing the SAME parser token
-- occurrence is a structural representation bridge, not an identity assertion.

CREATE OR REPLACE VIEW execution.semantic_pnf_factor_identity_support_v1 AS
SELECT edge.factor_id,
       edge.slot_ordinal,
       edge.role_symbol_id,
       edge.object_id AS factor_object_id,
       projection.source_object_id AS identity_source_object_id,
       projection.target_entity_id,
       projection.authority_class,
       projection.witness_ids,
       1::SMALLINT AS support_kind,
       NULL::BIGINT AS support_token_id
  FROM execution.semantic_pnf_hyperedge AS edge
  JOIN execution.semantic_pnf_identity_projection AS projection
    ON projection.source_object_id = edge.object_id
UNION ALL
SELECT edge.factor_id,
       edge.slot_ordinal,
       edge.role_symbol_id,
       edge.object_id AS factor_object_id,
       projection.source_object_id AS identity_source_object_id,
       projection.target_entity_id,
       projection.authority_class,
       projection.witness_ids,
       2::SMALLINT AS support_kind,
       factor_support.token_id AS support_token_id
  FROM execution.semantic_pnf_hyperedge AS edge
  JOIN execution.semantic_pnf_factor AS factor
    ON factor.factor_id = edge.factor_id
  JOIN execution.semantic_pnf_region AS factor_region
    ON factor_region.region_id = factor.region_id
  JOIN execution.semantic_pnf_object_token_support AS factor_support
    ON factor_support.object_id = edge.object_id
  JOIN execution.semantic_pnf_object_token_support AS identity_support
    ON identity_support.token_id = factor_support.token_id
   AND identity_support.object_id <> edge.object_id
  JOIN execution.semantic_pnf_identity_projection AS projection
    ON projection.source_object_id = identity_support.object_id
  JOIN execution.semantic_pnf_object AS identity_object
    ON identity_object.object_id = projection.source_object_id
  JOIN execution.semantic_pnf_region AS identity_region
    ON identity_region.region_id = identity_object.region_id
   AND identity_region.run_id = factor_region.run_id
   AND identity_region.document_id = factor_region.document_id;

-- Fail closed when one factor argument/authority is structurally supported by
-- projections to more than one canonical entity.  When several representations
-- support the SAME entity, choose one deterministic witness path.
CREATE OR REPLACE VIEW execution.semantic_pnf_factor_identity_support_unique_v1 AS
WITH unambiguous AS (
    SELECT factor_id, slot_ordinal, authority_class
      FROM execution.semantic_pnf_factor_identity_support_v1
     GROUP BY factor_id, slot_ordinal, authority_class
    HAVING count(DISTINCT target_entity_id) = 1
)
SELECT DISTINCT ON (support.factor_id, support.slot_ordinal, support.authority_class)
       support.*
  FROM execution.semantic_pnf_factor_identity_support_v1 AS support
  JOIN unambiguous
    ON unambiguous.factor_id = support.factor_id
   AND unambiguous.slot_ordinal = support.slot_ordinal
   AND unambiguous.authority_class = support.authority_class
 ORDER BY support.factor_id,
          support.slot_ordinal,
          support.authority_class,
          support.support_kind,
          support.identity_source_object_id,
          support.support_token_id NULLS FIRST;

