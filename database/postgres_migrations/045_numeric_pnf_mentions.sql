CREATE TABLE IF NOT EXISTS execution.semantic_pnf_mention (
    mention_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mention_digest BYTEA NOT NULL UNIQUE CHECK (octet_length(mention_digest) = 32),
    region_id BIGINT NOT NULL
        REFERENCES execution.semantic_pnf_region(region_id) ON DELETE CASCADE,
    sentence_id BIGINT NOT NULL
        REFERENCES execution.semantic_parser_sentence(sentence_id) ON DELETE CASCADE,
    mention_kind SMALLINT NOT NULL
        REFERENCES execution.semantic_pnf_mention_kind(kind_id) ON DELETE RESTRICT,
    start_char BIGINT NOT NULL CHECK (start_char >= 0),
    end_char BIGINT NOT NULL CHECK (end_char > start_char),
    head_token_id BIGINT NOT NULL
        REFERENCES execution.semantic_parser_token(token_id) ON DELETE RESTRICT,
    head_symbol_id BIGINT NOT NULL
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    entity_type_symbol_id BIGINT
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    grammatical_role_symbol_id BIGINT
        REFERENCES execution.semantic_symbol(symbol_id) ON DELETE RESTRICT,
    information_gain DOUBLE PRECISION NOT NULL CHECK (information_gain >= 0),
    representation_cost DOUBLE PRECISION NOT NULL CHECK (representation_cost >= 0),
    ambiguity_cost DOUBLE PRECISION NOT NULL CHECK (ambiguity_cost >= 0),
    promotion_score DOUBLE PRECISION NOT NULL,
    object_id BIGINT
        REFERENCES execution.semantic_pnf_object(object_id) ON DELETE SET NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (region_id, start_char, end_char, mention_kind)
